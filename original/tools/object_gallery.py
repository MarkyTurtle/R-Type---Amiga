#!/usr/bin/env python3
"""Build docs/OBJECTS.md: every object definition with a picture of its frames.

usage: python3 -I tools/object_gallery.py files/ gfx/objects/ docs/OBJECTS.md

Uses the definition search and BOB decoder from render_gfx.py.  Objects named
in the sources are listed under their label; add new names to NAMES below.
"""
import os, struct, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import render_gfx as R

NAMES = {
    (1, 0x4B99A): 'PataPata',
    (1, 0x4BA36): 'Bug',
    (1, 0x4BAA8): 'PStaff',
    (1, 0x4BB64): 'PStaffMissile',
    (1, 0x4BD02): 'Scant',
    (1, 0x4BD46): 'ScantBeam',
    (1, 0x4BD82): 'Bink',
    (1, 0x4BEA0): 'Cancer',
    (1, 0x4BF04): 'Shell',
    (1, 0x4BFCA): 'Tabrok',
    (1, 0x4C036): 'TabrokMissile',
    (1, 0x4C068): 'TabrokHomer',
    (1, 0x4C1CA): 'DobkeratopsTail',
    (1, 0x4C26C): 'DobkeratopsShot',
    (1, 0x4C22A): 'DobkeratopsCore',
}   # (level, definition address): name, as used in the source labels (Def_<name>)

def strip_image(frames, pal, path):
    w = sum(len(f[0]) + 2 for f in frames)
    h = max(len(f) for f in frames)
    im = Image.new('RGB', (w, h), (60, 0, 60))
    x = 0
    for f in frames:
        for yy, row in enumerate(f):
            for xx, v in enumerate(row):
                if v is not None:
                    im.putpixel((x + xx, yy), pal[v])
        x += len(f[0]) + 2
    im = im.resize((im.width * 2, im.height * 2), Image.NEAREST)
    im.save(path)

def main():
    files, out, md = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(out, exist_ok=True)
    blk = open(os.path.join(files, 'game_main_06000.bin'), 'rb').read()
    low6000 = bytearray(0x2D1BA); low6000[0x6000:0x6000 + len(blk)] = blk
    rel = os.path.relpath(out, os.path.dirname(md))
    lines = ['# R-Type (Amiga) – object gallery', '',
             'Every object definition found in the level files, with all its frames (level palette, 2× size). '
             'Generated by `tools/object_gallery.py`; labels match the sources (`Def_xxxxx` in `src/levels/levelN.s`). '
             'The engine\'s own definitions (explosions, POW Armor, power-ups) are in `gfx/engine_bobs.png`.', '',
             'Objects identified so far are listed under their R-Type name (the label in the source); the others under their address. Names are kept in `NAMES` in the script.', '']
    for n in range(1, 9):
        L = R.Level(files, n)
        ts, ds = struct.unpack('>II', L.a[2:10])
        defs = R.find_definitions(L, None, 0x4A300, 0x4A300 + ts + ds)
        starts = sorted({d['gfx'] for d in defs} | {L.map_ptr, L.map_src, L.music, R.B_BASE + len(L.b), 0x12950, 0x189D0})
        lines += [f'## Level {n}', '', '| Label | Frames | Size | HP | Fires | Score | Update | Spawn | Address |',
                  '|---|---|---|---|---|---|---|---|---|']
        for d in defs:
            raw = L.read(d['addr'], 0x28)
            hp, rate = struct.unpack('>HH', raw[8:12])
            upd, spn, score = struct.unpack('>III', raw[0x1C:0x28])
            fr = []
            for b in L.read(d['anim'], 64):
                if b >= 0x80: break
                fr.append(b)
            nxt = min([a for a in starts if a > d['gfx']] or [d['gfx'] + 64 * d['frame']])
            nf = max(1, min((max(fr) + 1) if fr else 1, (nxt - d['gfx']) // d['frame']))
            frames = []
            for i in range(min(nf, 16)):
                a = d['gfx'] + i * d['frame']
                data = low6000[a:a + d['frame']] if a < 0x2D1BA else L.read(a, d['frame'])
                if len(data) < d['frame']: break
                frames.append(R.bob_frame(bytes(data), d['lines'], d['words'], d['mask']))
            fn = f"level{n}_{d['addr']:05X}.png"
            strip_image(frames, L.palette, os.path.join(out, fn))
            hp_s = 'indestructible' if hp == 0xFFFF else (str(hp) if hp else '–')
            label = NAMES.get((n, d['addr']), f"{d['addr']:05X}")
            lines.append(f"| `Def_{label}` | ![]({rel}/{fn}) | {d['words'] * 16}×{d['lines']} ×{nf} | {hp_s} | "
                         f"{rate or '–'} | {f'{score:X}' if 0 < score < 0x10000 else '–'} | "
                         f"{(f'`Upd_{label}`' if (n, d['addr']) in NAMES else f'`${upd:05X}`') if upd else '–'} | "
                         f"{(f'`Spawn_{label}`' if (n, d['addr']) in NAMES else f'`${spn:05X}`') if spn else '–'} | {'`$%05X`' % d['addr']} |")
        lines.append('')
    open(md, 'w').write('\n'.join(lines))
    print('written', md)

if __name__ == '__main__':
    main()
